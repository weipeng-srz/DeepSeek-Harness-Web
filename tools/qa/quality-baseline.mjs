import fs from 'node:fs'
import path from 'node:path'
import { ROOT, createSandbox, launchBrowser, loginPage, sleep } from './quality-harness.mjs'

const label = process.env.QA_LABEL || 'baseline'
const out = path.join(ROOT, 'reports/quality', label)
fs.mkdirSync(out, { recursive: true })
const results = []
const record = (name, ok, evidence = {}) => { results.push({ name, status: ok ? 'passed' : 'failed', evidence }); console.log(`${ok ? 'PASS' : 'FAIL'} ${name} ${JSON.stringify(evidence)}`) }
const sandbox = await createSandbox({ port: Number(process.env.QA_PORT || 8797), label })
fs.writeFileSync(path.join(out, 'sandbox.json'), JSON.stringify({ path: sandbox.dir, base: sandbox.base, testOnly: true, sourceFiles: sandbox.sourceFiles }, null, 2))
console.log(`SANDBOX ${sandbox.base} ${sandbox.dir}`)
const browser = await launchBrowser()
try {
  // Synthetic fixture only. No production/local user data is read or copied.
  await sandbox.api('/api/backup/import', { method: 'POST', body: JSON.stringify({ conversations: ['Alpha', 'Beta', 'Gamma'].map(title => ({ title: `QA ${title}`, engine: 'dsr', messages: [{ role: 'user', text: `Find ${title} fixture` }, { role: 'assistant', text: `# ${title}\n\nQuality fixture response.\n\n| Field | Value |\n| --- | --- |\n| Status | Ready |\n\n\`\`\`js\nconsole.log("fixture")\n\`\`\`` }] })) }) })
  const list = (await sandbox.api('/api/conversations?limit=100')).body.conversations
  const alpha = list.find(x => x.title.includes('Alpha'))
  const beta = list.find(x => x.title.includes('Beta'))
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, serviceWorkers: 'block' })
  const page = await context.newPage()
  const pageErrors = []
  page.on('pageerror', error => pageErrors.push(error.message))
  await loginPage(page, sandbox)
  record('authenticated logout control discoverable', await page.locator('#logoutBtn').isVisible(), { hidden: await page.locator('#logoutBtn').getAttribute('hidden') })
  record('login shell and fixture list', await page.locator('#shell').isVisible() && await page.locator('#convList .conv-item').count() === 3)
  await page.screenshot({ path: path.join(out, 'desktop-home.png'), fullPage: true })
  await page.goto(`${sandbox.base}/c/${alpha.id}`)
  await page.waitForTimeout(900)
  const firstDeepLink = page.url().includes(alpha.id) && await page.locator('#thread .msg').count() === 2
  await page.reload()
  await page.waitForTimeout(900)
  record('direct deep link survives empty home cache and reload', firstDeepLink && page.url().includes(alpha.id) && await page.locator('#thread .msg').count() === 2, { firstDeepLink, pathname: new URL(page.url()).pathname })
  await page.locator('#newChat').click()
  await page.locator('#convSearch').fill('Alpha')
  await page.waitForTimeout(650)
  record('title and message search', await page.locator('#convList .conv-item').count() === 1 && (await page.locator('#convResultCount').innerText()).length > 0)
  await page.locator('#convSearchClear').click()
  await page.waitForTimeout(350)
  await page.locator(`[data-id="${alpha.id}"] .conv-main`).click()
  await page.locator('#thread .msg').first().waitFor()
  record('conversation opens with messages and route', page.url().includes(alpha.id) && await page.locator('#thread .msg').count() === 2)
  await page.locator(`[data-id="${alpha.id}"] .conv-more`).click()
  await page.locator('#convPopover [data-action="rename"]').click()
  await page.locator('#renameInput').fill('QA Alpha renamed')
  await page.locator('#renameSave').click()
  await page.waitForTimeout(300)
  record('rename saves title and closes modal', await page.locator('#topbarName').innerText() === 'QA Alpha renamed' && !await page.locator('#renameModal').isVisible())
  await page.locator('#input').fill('QA retained draft')
  await page.locator(`[data-id="${beta.id}"] .conv-main`).click()
  await page.waitForTimeout(250)
  await page.locator(`[data-id="${alpha.id}"] .conv-main`).click()
  await page.waitForTimeout(250)
  record('per-conversation draft restoration', await page.locator('#input').inputValue() === 'QA retained draft')
  await page.locator('#settingsBtn').click()
  record('settings opens accessible dialog', await page.locator('#settingsSheet [role="dialog"]').isVisible())
  await page.locator('[data-theme-option="dark"]').click()
  record('dark theme selection', await page.locator('html').getAttribute('data-theme') === 'dark')
  await page.screenshot({ path: path.join(out, 'desktop-settings-dark.png'), fullPage: true })
  await page.keyboard.press('Escape')
  record('settings Escape close', !await page.locator('#settingsSheet').isVisible())
  await page.reload()
  await page.locator('#shell').waitFor({ state: 'visible' })
  record('theme persists after reload', await page.locator('html').getAttribute('data-theme') === 'dark')
  await page.locator('#settingsBtn').click()
  await page.locator('[data-theme-option="light"]').click()
  await page.keyboard.press('Escape')
  // Race a genuine server response, preserving the real request and JSON schema.
  await page.route(`**/api/conversations/${alpha.id}`, async route => { const response = await route.fetch(); await sleep(900); await route.fulfill({ response }) })
  await page.locator(`[data-id="${alpha.id}"] .conv-main`).click()
  await page.waitForTimeout(80)
  await page.locator(`[data-id="${beta.id}"] .conv-main`).click()
  await page.waitForTimeout(1300)
  record('latest conversation selection wins response race', (await page.locator('#topbarName').innerText()).includes('Beta'), { title: await page.locator('#topbarName').innerText(), route: new URL(page.url()).pathname })
  await page.unroute(`**/api/conversations/${alpha.id}`)
  await page.goto(`${sandbox.base}/c/nonexistent-quality-fixture`)
  await page.locator('#shell').waitFor({ state: 'visible' })
  await page.waitForTimeout(750)
  record('invalid conversation ends loading state', await page.locator('.thread-skeleton').count() === 0, { skeletons: await page.locator('.thread-skeleton').count(), toast: await page.locator('.toast').allTextContents() })
  await page.screenshot({ path: path.join(out, 'invalid-conversation.png'), fullPage: true })
  await page.locator('#newChat').click()
  // Transport failure is deliberately injected; no model is invoked or charged.
  await page.route('**/api/conversations/*/chat', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: 'QA simulated engine unavailable' }) }))
  await page.locator('#input').fill('QA send failure route test')
  await page.locator('#sendBtn').click()
  await page.waitForTimeout(650)
  const createdId = await page.evaluate(() => localStorage.getItem('dsh.current'))
  record('newly created conversation updates deep-link route', Boolean(createdId) && new URL(page.url()).pathname === `/c/${createdId}`, { pathname: new URL(page.url()).pathname, conversationCreated: Boolean(createdId) })
  record('chat failure presents retry action', await page.locator('#thread').innerText().then(text => text.includes('QA simulated engine unavailable') && text.includes('重试')))
  await page.unroute('**/api/conversations/*/chat')
  await page.locator('#input').fill('')
  await page.locator('#fileInput').setInputFiles({ name: 'qa-note.txt', mimeType: 'text/plain', buffer: Buffer.from('Quality fixture attachment') })
  await page.waitForTimeout(250)
  record('attachment can be staged', await page.locator('#attachmentTray').innerText().then(text => text.includes('qa-note.txt')).catch(() => false))
  for (const width of [320, 390, 768, 1440]) {
    await page.setViewportSize({ width, height: width < 500 ? 844 : 1000 })
    await page.waitForTimeout(200)
    const overflow = await page.evaluate(() => ({ viewport: innerWidth, document: document.documentElement.scrollWidth, body: document.body.scrollWidth }))
    record(`layout has no horizontal overflow at ${width}`, overflow.document <= width + 1 && overflow.body <= width + 1, overflow)
    await page.screenshot({ path: path.join(out, `responsive-${width}.png`), fullPage: true })
    if (width < 900) {
      await page.locator('#menuBtn').click()
      record(`sidebar opens at ${width}`, await page.locator('#menuBtn').getAttribute('aria-expanded') === 'true')
      await page.keyboard.press('Escape')
      record(`sidebar Escape close at ${width}`, await page.locator('#menuBtn').getAttribute('aria-expanded') === 'false')
    }
  }
  for (const shortcut of ['Meta+k', 'Meta+p']) {
    await page.keyboard.press(shortcut)
    await page.keyboard.press(shortcut)
    await page.keyboard.press('Escape')
    await page.waitForTimeout(100)
    record(`repeated ${shortcut} does not leave page inert`, !(await page.locator('#shell').evaluate(el => el.inert)), { inert: await page.locator('#shell').evaluate(el => el.inert) })
    await page.reload()
    await page.locator('#shell').waitFor({ state: 'visible' })
  }
  record('no uncaught browser exceptions', pageErrors.length === 0, { errors: pageErrors })
  const perf = await page.evaluate(() => { const n = performance.getEntriesByType('navigation')[0]; return { domContentLoadedMs: Math.round(n.domContentLoadedEventEnd), loadMs: Math.round(n.loadEventEnd), encodedBytes: performance.getEntriesByType('resource').reduce((s, r) => s + r.encodedBodySize, 0) } })
  fs.writeFileSync(path.join(out, 'performance.json'), JSON.stringify(perf, null, 2))
  // Real API validation against the fresh sandbox.
  const unauth = await fetch(sandbox.base + '/api/conversations')
  record('API rejects unauthenticated requests', unauth.status === 401)
  const emptyTitle = await sandbox.api(`/api/conversations/${alpha.id}`, { method: 'PATCH', body: JSON.stringify({ title: ' ' }) })
  record('API rejects blank conversation titles', emptyTitle.status === 400)
  const crossSite = await sandbox.api(`/api/conversations/${alpha.id}`, { method: 'PATCH', headers: { Origin: 'https://evil.example' }, body: JSON.stringify({ title: 'forbidden' }) })
  record('API rejects cross-origin mutation', crossSite.status === 403)
  const archived = await sandbox.api(`/api/conversations/${alpha.id}`, { method: 'PATCH', body: JSON.stringify({ archived: true }) })
  const archives = await sandbox.api('/api/conversations?archived=1')
  record('API archive appears in archive list', archived.status === 200 && archives.body.conversations.some(x => x.id === alpha.id))
  const duplicate = await sandbox.api(`/api/conversations/${beta.id}/duplicate`, { method: 'POST' })
  const duplicateDetail = duplicate.body.conversation?.id ? await sandbox.api(`/api/conversations/${duplicate.body.conversation.id}`) : null
  record('API duplicate preserves conversation messages', duplicate.status === 201 && duplicateDetail?.body?.conversation?.messages?.length === 2)
  const deletion = await sandbox.api(`/api/conversations/${beta.id}`, { method: 'DELETE' })
  const restore = await sandbox.api(`/api/conversations/${beta.id}/restore`, { method: 'POST' })
  record('API delete can be undone in window', deletion.status === 200 && restore.status === 200)
  const backup = await sandbox.api('/api/backup')
  record('API backup returns all synthetic conversations', backup.status === 200 && backup.body.count >= 4)
  await context.close()
} catch (error) {
  results.push({ name: 'harness execution', status: 'blocked', evidence: { message: error.stack } })
  console.error(error.stack)
} finally {
  const report = { label, generatedAt: new Date().toISOString(), environment: { browser: `Chrome ${browser.version()} via Playwright, headless`, node: process.version, fixture: 'synthetic, isolated storage and credential homes', sandbox: sandbox.dir, baselineSource: 'source snapshot copied when harness starts', sourceFiles: sandbox.sourceFiles }, results, totals: { passed: results.filter(x => x.status === 'passed').length, failed: results.filter(x => x.status === 'failed').length, blocked: results.filter(x => x.status === 'blocked').length } }
  fs.writeFileSync(path.join(out, 'results.json'), JSON.stringify(report, null, 2))
  console.log(JSON.stringify(report.totals))
  await browser.close()
  if (process.env.QA_KEEP_SERVER === '1') { sandbox.child.unref(); console.log('Keeping isolated sandbox server for independent review') } else await sandbox.stop()
}
