import fs from 'node:fs'
import { DESKTOP_PATCH, GENERATED_PATCH } from './config.mjs'

function extractTopLevelItem(source, id) {
  const lines = source.split('\n')
  const pattern = new RegExp(`^- id:\\s*["']?${id.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}["']?\\s*$`)
  const start = lines.findIndex((line) => pattern.test(line))
  if (start < 0) return null
  let end = lines.length
  for (let i = start + 1; i < lines.length; i += 1) {
    if (/^- /.test(lines[i])) {
      end = i
      break
    }
  }
  const block = lines.slice(start, end)
  while (block.length && (/^\s*$/.test(block.at(-1)) || /^\s*#/.test(block.at(-1)))) block.pop()
  return block.join('\n')
}

/**
 * The desktop profile carries the machine's real model route (provider,
 * endpoint, model ids). The shipped headless profile pins deepseek-official,
 * which has no key on this machine, so we mirror the desktop selection and
 * re-enable the managed credential store the headless patch disables.
 */
export function writeHeadlessPatch() {
  const header = [
    '# Generated by dsh-chat. Do not edit: it is rewritten from the desktop',
    '# profile on every server start so the chat page follows the GUI model.',
  ]
  const credentialRows = [
    '- id: credentials',
    '  disabled: false',
    '- id: authorization',
    '  disabled: false',
    '- id: deepseek-account',
    '  disabled: false',
  ]
  let desktop = ''
  try {
    desktop = fs.readFileSync(DESKTOP_PATCH, 'utf8')
  } catch {
    desktop = ''
  }
  const blocks = []
  for (const id of ['agent-default-model', 'llm-pi-ai']) {
    const block = desktop ? extractTopLevelItem(desktop, id) : null
    if (block) blocks.push(block)
  }
  const body = [...header, '', ...credentialRows, ...(blocks.length ? [''] : []), ...blocks].join('\n')
  fs.writeFileSync(GENERATED_PATCH, body + '\n', 'utf8')
  return { patchPath: GENERATED_PATCH, mirrored: blocks.length > 0 }
}
